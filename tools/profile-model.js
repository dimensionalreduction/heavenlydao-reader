// The playground's translate.js (vendor/translate.js here, an ES module that the playground's page and the library's page load) as a script the extension's
// background loads (Chrome's service worker cannot import a module): the same code, its exports as one global, ProfileModel. build.js writes it into dist as
// profile-model.js, and the tests load it the same way, so a translation profile is used here as it is there (profile-translate.js).
const fs = require("fs");
const path = require("path");

const SOURCE = path.join(__dirname, "..", "vendor", "translate.js");
function profileModelText(source = SOURCE) {
  const src = fs.readFileSync(source, "utf8");
  const names = [...src.matchAll(/^export\s+(?:async\s+)?(?:function\s*\*?\s*|const\s+)([A-Za-z_$][\w$]*)/gm)].map((m) => m[1]);
  return "// GENERATED by build.js from vendor/translate.js (tools/profile-model.js). Do not edit by hand.\nvar ProfileModel = (function () {\n" +
    src.replace(/^export\s+/gm, "") + "\nreturn { " + names.join(", ") + " };\n})();\n";
}

module.exports = { profileModelText, SOURCE };
